"""
crud.py — Data-access functions for the Polar Logistics backend.

All functions accept a SQLAlchemy ``Session`` as their first argument and
return ORM model instances.  They are intentionally thin: no HTTP concerns,
no event-replay logic, no business orchestration.  That separation keeps the
data layer testable in isolation and lets the upcoming ``sync_engine.py``
compose these primitives into higher-level event handlers.

**Query style chosen: Legacy ``db.query()`` (1.x-style)**

Both ``db.query(Model)`` and ``db.execute(select(Model))`` are fully supported
in SQLAlchemy 2.0.  We use ``db.query()`` throughout because:
  • It returns ORM instances directly — no need to unpack ``Row`` / ``ScalarResult``.
  • It is terser for the simple single-table CRUD this module performs.
  • SQLAlchemy 2.0 still supports it; it is *not* deprecated, only the
    ``Query.from_self()`` / ``Query.with_parent()`` helpers are.

If this project later needs Core-style bulk operations or CTEs, a migration to
``select()`` for those specific queries would be straightforward.
"""

