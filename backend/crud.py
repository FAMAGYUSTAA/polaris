def get_inventory(
    db: Session,
    station_id: Optional[str] = None,
) -> List[InventoryItem]:
    """
    Return all inventory items, optionally filtered by station.

    When ``station_id`` is ``None`` every item across all stations is returned —
    useful for the central aggregation dashboard.
    """
    query = db.query(InventoryItem)
    if station_id is not None:
        query = query.filter(InventoryItem.station_id == station_id)
    return query.all()


def get_inventory_item_by_sku(
    db: Session,
    station_id: str,
    sku: str,
) -> Optional[InventoryItem]:
    """
    Look up a single inventory row by its (station_id, sku) composite key.

    Returns ``None`` if no matching row exists — callers should handle that case
    (e.g. by creating the item first via ``create_inventory_item``).
    """
    return (
        db.query(InventoryItem)
        .filter(
            InventoryItem.station_id == station_id,
            InventoryItem.sku == sku,
        )
        .first()
    )


def create_inventory_item(
    db: Session,
    item: InventoryItemCreate,
) -> InventoryItem:
    """
    Insert a new inventory item.

    The ``id`` and ``updated_at`` fields are auto-generated by the ORM defaults
    defined in ``models.py``.
    """
    db_item = InventoryItem(**item.model_dump(exclude_unset=True, exclude_none=True))
    db.add(db_item)
    db.commit()
    db.refresh(db_item)
    return db_item


def apply_inventory_delta(
    db: Session,
    item_id: str,
    delta: float,
) -> InventoryItem:
    """
    Apply a quantity delta to an existing inventory item: **Qₜ₊₁ = Qₜ + Δ**.

    This is the fundamental stock-movement primitive.  Every consumption,
    receipt, or adjustment ultimately calls this function.

    **Negative-result handling:**
    Real-world sensors (e.g. fuel-tank gauges at −40 °C) can be imprecise,
    occasionally producing deltas that would drive the stored quantity below
    zero.  Rather than raising an exception and blocking the entire sync batch,
    we *clamp* the result to ``0.0`` and log a warning so that the anomaly is
    visible to station operators without halting logistics operations.

    Raises:
        ValueError: If no inventory item with the given ``item_id`` exists.
    """
    db_item = db.query(InventoryItem).filter(InventoryItem.id == item_id).first()
    if db_item is None:
        raise ValueError(f"InventoryItem with id '{item_id}' not found.")

    new_quantity = db_item.quantity + delta

    if new_quantity < 0:
        logger.warning(
            "Inventory item '%s' (SKU %s @ %s): delta %.4f would result in "
            "negative quantity (%.4f → %.4f). Clamping to 0.0.",
            item_id,
            db_item.sku,
            db_item.station_id,
            delta,
            db_item.quantity,
            new_quantity,
        )
        new_quantity = 0.0

    db_item.quantity = new_quantity
    # Explicitly touch updated_at so the onupdate trigger fires even if
    # SQLAlchemy's dirty-detection doesn't catch the float change.
    db_item.updated_at = datetime.now(timezone.utc)

    db.commit()
    db.refresh(db_item)
    return db_item


