def update_personnel_status(
    db: Session,
    person_id: str,
    status: str,
) -> Personnel:
    """
    Update a person's location status (INSIDE_BASE / FIELD_MISSION / MEDICAL_BAY)
    and bump ``last_seen`` to the current UTC time.

    This is called when processing ``PERSONNEL_STATUS_CHANGE`` or
    ``FIELD_CHECKOUT`` / ``FIELD_CHECKIN`` sync events.

    Raises:
        ValueError: If no personnel record with the given ``person_id`` exists.
    """
    db_person = db.query(Personnel).filter(Personnel.id == person_id).first()
    if db_person is None:
        raise ValueError(f"Personnel with id '{person_id}' not found.")

    db_person.status = status
    db_person.last_seen = datetime.now(timezone.utc)

    db.commit()
    db.refresh(db_person)
    return db_person


