    from datetime import datetime, timezone
    exp = db.query(PlannedExpedition).filter(PlannedExpedition.id == expedition_id).first()
    if exp:
        exp.status = "CANCELLED"
        exp.cancelled_at = datetime.now(timezone.utc)
        db.commit()
        return True
    return False


