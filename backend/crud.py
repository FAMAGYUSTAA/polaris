def get_ledger_event_by_client_id(
    db: Session,
    client_event_id: str,
) -> Optional[SyncLedger]:
    """
    Look up a ledger entry by its client-generated idempotency key.

    This is the first thing the sync endpoint checks before processing an
    inbound event: if this function returns a row, the event has already been
    applied and should be skipped (reported as a duplicate in ``rejected_ids``).
    """
    return (
        db.query(SyncLedger)
        .filter(SyncLedger.client_event_id == client_event_id)
        .first()
    )


def insert_ledger_event(
    db: Session,
    event: SyncEventIn,
) -> SyncLedger:
    """
    Persist a raw client event into the append-only SyncLedger.

    Field mapping from the inbound schema:
        SyncEventIn.id        → SyncLedger.client_event_id
        SyncEventIn.timestamp → SyncLedger.client_timestamp

    ``SyncLedger.id`` (the server-side row PK) and ``server_received_at``
    are auto-generated by the ORM defaults.
    """
    db_event = SyncLedger(
        client_event_id=event.id,
        station_id=event.station_id,
        event_type=event.event_type,
        payload=event.payload,
        client_timestamp=event.timestamp,
    )
    db.add(db_event)
    db.commit()
    db.refresh(db_event)
    return db_event


def get_all_ledger_events(
    db: Session,
    station_id: Optional[str] = None,
    since: Optional[datetime] = None,
) -> List[SyncLedger]:
    """
    Retrieve ledger events ordered by ``client_timestamp`` ascending.

    Chronological ordering is critical: during a full replay (e.g. rebuilding
    materialised state after data corruption) events must be applied in the
    exact order they originally occurred at the station — *not* the order they
    happened to arrive at the server.

    Optional filters:
        ``station_id`` — restrict to events from a single station.
        ``since``      — only return events whose ``client_timestamp`` is at or
                         after this datetime (useful for incremental pulls).
    """
    query = db.query(SyncLedger)
    if station_id is not None:
        query = query.filter(SyncLedger.station_id == station_id)
    if since is not None:
        query = query.filter(SyncLedger.client_timestamp >= since)
    return query.order_by(SyncLedger.client_timestamp.asc()).all()

